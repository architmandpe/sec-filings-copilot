"""Web demo: ask a question about the SEC filings, see the passages retrieved and, on a Mac, the cited answer.

Run locally:  python app.py   (opens http://127.0.0.1:7860)

Uses the Week 3 pipeline: company/fiscal-year filter, hybrid search (dense + BM25), cross-encoder reranker.
The answer step needs MLX (Apple silicon). Where MLX isn't installed (e.g. a free Hugging Face Space, Linux CPU)
the app runs retrieval only and says so.
"""

import html
import importlib.util

import gradio as gr

from agent.answer import GEN_MODEL, RAG, TOP_K

GENERATE = importlib.util.find_spec("mlx_lm") is not None  # MLX installed -> generate answers
# dev questions the pipeline answered correctly and faithfully (judge run 20261106-181326), one per type,
# plus two correct refusals (a forecast; executive pay, which is in the proxy statement, not the 10-K)
EXAMPLES = [
    "What was Apple's gross margin percentage in fiscal 2024?",
    "How much did Apple's total net sales grow from fiscal 2023 to fiscal 2025, in percent?",
    "Where are Apple's outsourcing partners that manufacture its hardware products primarily located, "
    "according to its fiscal 2024 10-K?",
    "What segments did Microsoft use to report its financial performance in fiscal 2023?",
    "What will Nike's revenue be in fiscal 2030?",
    "How much was Apple's CEO paid in fiscal 2024?",
]

rag = RAG(filter_filings=True, search="hybrid", rerank=True, load_generator=GENERATE)


def sources_markdown(chunks: list[dict]) -> str:
    """The retrieved passages: one line of source information each, the full text folded underneath."""
    parts = [f"### Retrieved passages (top {TOP_K})"]
    for n, c in enumerate(chunks, 1):
        header = (f"**{n}. `{c['id']}`**: {c['company']}, {c['form']} FY{c['fiscal_year']} {c['fiscal_period']}, "
                  f"Item {c['item']} {c['title']} · reranker score {c['score']:.2f} · [filing on EDGAR]({c['url']})")
        parts.append(f"{header}\n\n<details><summary>Show text</summary>\n\n<pre style='white-space: pre-wrap'>"
                     f"{html.escape(c['text'])}</pre>\n\n</details>")
    return "\n\n".join(parts)


def ask(question: str):
    """Yield (answer, sources) as they become available: sources first, then the answer as it is generated."""
    question = question.strip()
    if not question:
        yield "Type a question first.", ""
        return
    chunks = rag.retrieve(question)
    sources = sources_markdown(chunks)
    if not GENERATE:
        yield ("*Retrieval-only demo: answers are generated by a local LLM (Qwen3-8B on Apple MLX), which this "
               "server can't run. Below are the passages it would answer from.*"), sources
        return
    yield "*Generating...*", sources
    for text in rag.stream(question, chunks):
        yield text, sources


with gr.Blocks(title="SEC Filings Copilot") as demo:
    gr.Markdown(
        "# SEC Filings Copilot\n"
        "Questions about 75 10-K and 10-Q filings from 32 companies, answered with citations, or refused when the "
        "filings don't contain the answer. Runs on open-source models"
        + (f" (`{GEN_MODEL}` for answers)." if GENERATE else "; this hosted version shows retrieval only."))
    question = gr.Textbox(label="Question", placeholder="e.g. What was Apple's gross margin percentage in fiscal 2024?")
    button = gr.Button("Ask", variant="primary")
    gr.Examples(EXAMPLES, inputs=question)
    answer = gr.Markdown(label="Answer")
    sources = gr.Markdown()
    button.click(ask, inputs=question, outputs=[answer, sources])
    question.submit(ask, inputs=question, outputs=[answer, sources])


if __name__ == "__main__":
    demo.launch()
